    fun search(query: String): List<Plant> {
        if (query.isBlank()) return emptyList()
        val q = query.trim().lowercase()
        return plants.filter { plant ->
            plant.name.lowercase().contains(q) ||
            plant.latinName.lowercase().contains(q)
        }
    }
